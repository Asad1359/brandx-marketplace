import api from './api';

/*
|--------------------------------------------------------------------------
| GET ALL BAGS
|--------------------------------------------------------------------------
*/

export const getAll = () => {
    return api.get('/bags');
};

/*
|--------------------------------------------------------------------------
| GET SINGLE BAG
|--------------------------------------------------------------------------
*/

export const get = (id) => {
    return api.get(`/bags/${id}`);
};

/*
|--------------------------------------------------------------------------
| GET SINGLE BAG - ALIAS
|--------------------------------------------------------------------------
*/

export const getById = get;

/*
|--------------------------------------------------------------------------
| CREATE BAG
|--------------------------------------------------------------------------
*/

export const create = (data) => {
    return api.post('/bags', data);
};

/*
|--------------------------------------------------------------------------
| UPDATE BAG
|--------------------------------------------------------------------------
*/

export const update = (id, data) => {
    return api.put(`/bags/${id}`, data);
};

/*
|--------------------------------------------------------------------------
| DELETE BAG
|--------------------------------------------------------------------------
*/

export const remove = (id) => {
    return api.delete(`/bags/${id}`);
};

/*
|--------------------------------------------------------------------------
| DEFAULT SERVICE
|--------------------------------------------------------------------------
*/

const bagService = {
    getAll,
    get,
    getById,
    create,
    update,
    remove,
};

export default bagService;